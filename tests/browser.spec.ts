import { expect, test } from '@playwright/test';
test('laboratory compiles real shaders, controls the material and sleeps at rest',async({page})=> {
  const errors: string[] = []; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/'); await expect(page.locator('#material-canvas')).toHaveAttribute('data-glass-context','ready');
  await expect.poll(()=>page.evaluate(()=> (window as any).glassLab.renderer.stats.frames)).toBeGreaterThan(2);
  await page.getByRole('button',{name:'Reduced motion',exact:false}).click();
  await page.getByRole('button',{name:'Clear',exact:true}).click();
  await expect(page.locator('#frost-value')).toHaveText('8%');
  await page.getByRole('button',{name:'Test grid',exact:true}).click();
  await page.getByRole('button',{name:'Merge surfaces',exact:false}).click();
  await expect(page.locator('#fusion-lens')).toBeVisible();
  await page.getByRole('button',{name:'Open material menu'}).click();
  await expect(page.locator('#material-menu')).toBeVisible(); await page.keyboard.press('Escape');
  await expect(page.locator('#material-menu')).toBeHidden();
  await expect.poll(()=>page.evaluate(()=>(window as any).glassLab.renderer.idle),{timeout:10000}).toBe(true);
  const a = await page.evaluate(()=> (window as any).glassLab.renderer.stats);
  await page.waitForTimeout(300);
  const b = await page.evaluate(()=> (window as any).glassLab.renderer.stats);
  expect(b.frames).toBe(a.frames); expect(b.uploads).toBe(a.uploads); expect(b.blurPasses).toBe(a.blurPasses);
  expect(errors).toEqual([]);
  await page.screenshot({path:'artifacts/laboratory-desktop.png',fullPage:true});
});
test('GPU lens bends the backdrop, leaves external pixels intact, and reuses blur',async({page})=> {
  await page.goto('/tests/harness.html');
  const baseline: number[] = await page.evaluate(()=> (window as any).testGlass.capture());
  await page.evaluate(()=> (window as any).testGlass.surface.material({variant:'clear',frost:0,thickness:24,edgeWidth:24,refraction:22,dispersion:0,saturation:1,highlight:0,shadow:0},false));
  const lens: number[] = await page.evaluate(()=> (window as any).testGlass.capture());
  const delta = (x: number,y: number) => { const i=(y*320+x)*4; return Math.abs(baseline[i]-lens[i])+Math.abs(baseline[i+1]-lens[i+1])+Math.abs(baseline[i+2]-lens[i+2]); };
  expect(delta(15,180)).toBeLessThan(3); expect(delta(160,120)).toBeLessThan(4);
  expect(Math.max(...Array.from({length:18},(_,i)=>delta(82+i,120)))).toBeGreaterThan(70);
  const before = await page.evaluate(()=> (window as any).testGlass.renderer.stats);
  await page.evaluate(()=> (window as any).testGlass.surface.move({x:120}));
  await page.waitForTimeout(1000);
  const after = await page.evaluate(()=> (window as any).testGlass.renderer.stats);
  expect(after.frames).toBeGreaterThan(before.frames); expect(after.uploads).toBe(before.uploads); expect(after.blurPasses).toBe(before.blurPasses);
  const glError = await page.evaluate(()=> (document.querySelector('canvas')!.getContext('webgl2')!).getError());
  expect(glError).toBe(0);
});
test('accessibility is live and context loss restores resources',async({page})=> {
  await page.emulateMedia({ reducedMotion:'reduce' }); await page.goto('/tests/harness.html');
  expect(await page.evaluate(()=> (window as any).testGlass.renderer.accessibility.reducedMotion)).toBe(true);
  await page.evaluate(()=> { const t=(window as any).testGlass; t.surface.material({variant:'regular'}); t.surface.move({x:150}); });
  await page.evaluate(()=> (window as any).testGlass.capture());
  expect(await page.evaluate(()=> (window as any).testGlass.surface.rect.x)).toBe(150);
  await page.evaluate(()=> { const gl=document.querySelector('canvas')!.getContext('webgl2')!, ext=gl.getExtension('WEBGL_lose_context'); (window as any).lossExt=ext; ext?.loseContext(); });
  await expect(page.locator('canvas')).toHaveAttribute('data-glass-context','lost');
  await page.evaluate(()=> (window as any).lossExt.restoreContext());
  await expect(page.locator('canvas')).toHaveAttribute('data-glass-context','ready');
  const pixels: number[] = await page.evaluate(()=> (window as any).testGlass.capture());
  expect(pixels.some((n,i)=>i%4!==3&&n>100)).toBe(true);
  await page.evaluate(()=> (window as any).testGlass.renderer.dispose());
  await expect(page.locator('canvas')).toHaveAttribute('data-glass-context','disposed');
});
